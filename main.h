//**********************************************************************************
// *** プロトタイプ宣言 ***
//**********************************************************************************
template<class T> void SafeRelease(T *&pRelease)
{ // 安全なCOMオブジェクト解放処理
	if (pRelease != nullptr)
	{ // nullptrでなければ解放
		pRelease->Release();
		pRelease = nullptr;
	}
}

template<class T> void SafeUniqueUninit(std::unique_ptr<T> &ptr)
{ // ユニークポインタのバッファ解放処理
	if (ptr != nullptr)
	{ // nullptrでなければ解放
		ptr->Uninit();
		ptr.reset();
	}
}
