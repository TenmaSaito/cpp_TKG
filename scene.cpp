#include "scene.h"
#include "game.h"

//==================================================================================
// --- モードの設定処理 (pOutに代入後初期化) ---
//==================================================================================
CScene *CScene::Create(const MODE mode, std::unique_ptr<CScene> &rpOut)
{
	CScene *pScene = nullptr;		// 生成したシーン

	// モード別にインスタンス生成
	switch (mode)
	{
	case MODE_GAME:		// ゲームシーンを生成
		pScene = new CGame;
		break;
	}

	// ポインタ設定
	rpOut.reset(pScene);

	if (pScene != nullptr)
	{ // 生成成功時、シーンの初期化
		pScene->Init();
	}

	return pScene;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CScene::CScene(const MODE mode)
{ // メンバ変数のクリア
	m_mode = mode;
}

