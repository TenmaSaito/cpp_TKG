#ifndef _SINGLETON_H_		// インクルードガード
#define _SINGLETON_H_

//**********************************************************************************
// *** シングルトンインターフェース ***
//**********************************************************************************
template<class T> class ISingleton
{
public:
	static T *GetInstance(void);

protected:
	ISingleton() = default;
	~ISingleton() = default;
};

//==================================================================================
// --- インスタンス取得処理 ---
//==================================================================================
template<class T> T *ISingleton<T>::GetInstance(void)
{
	static T instance;
	return &instance;
}
#endif