#include "nextInfo.h"
#include "object2D.h"
#include "texture.h"

//**********************************************************************************
// *** 定数宣言 ***
//**********************************************************************************
namespace
{
	constexpr std::string_view NORMAL_BASE = "data/TEXTURE/nextInfo.png";		// 通常のBaseテクスチャ
	constexpr std::string_view ANGRY_BASE = "data/TEXTURE/angry.png";			// 通常のAngryテクスチャ
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CNextInfo::CNextInfo()
{ // タイプ指定
	SetType(TYPE_NEXTINFO);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CNextInfo::~CNextInfo()
{
}

//==================================================================================
// --- 生成処理 ---
//==================================================================================
CNextInfo *CNextInfo::Create(void)
{
	CNextInfo *pObject = new CNextInfo;		// 生成したオブジェクト
	if (pObject != nullptr)
	{ // nullではないなら初期化
		pObject->Init();
	}

	return pObject;
}

//==================================================================================
// --- 初期化処理 ---
//==================================================================================
HRESULT CNextInfo::Init(void)
{
	// ベースのUIの設定
	CObject2D::Info info;
	info.pos = Vector3(SCREEN_MIDDLE.x, SCREEN_MIDDLE.y * 0.75f, 0.0f);
	info.size = Vector2(SCREEN_SIZE.x * 0.75f, 100.0f);
	info.pTexturePath = NORMAL_BASE.data();

	// ベースのUIを作成
	m_pBase = CObject2D::Create(info);
	return S_OK;
}

//==================================================================================
// --- 終了処理 ---
//==================================================================================
void CNextInfo::Uninit(void)
{
	if (m_pBase != nullptr)
	{ // ベースの破棄
		m_pBase->Uninit();
		m_pBase = nullptr;
	}

	if (m_pNext != nullptr)
	{ // 次に取得するアイテム表示の破棄
		m_pNext->Uninit();
		m_pNext = nullptr;
	}

	// 解放処理
	CObject::Release();
}

//==================================================================================
// --- 更新処理 ---
//==================================================================================
void CNextInfo::Update(void)
{
	if (m_nAngryCount < 0) return;		// テクスチャの再設定の繰り返しを防止するために、early return

	m_nAngryCount--;
	if (m_nAngryCount > 0) return;		// 怒りのフレーム数が0以上の場合、スキップ

	// 通常のテクスチャに変更
	m_pBase->BindTexture(CTexture::GetInstance()->Register(NORMAL_BASE));
}

//==================================================================================
// --- 次のアイテム表示ポリゴンの設定処理 ---
//==================================================================================
void CNextInfo::SetNext(CObject2D *pNext)
{
	if (m_pNext != nullptr)
	{ // 次に取得するアイテム表示の破棄
		m_pNext->Uninit();
		m_pNext = nullptr;
	}

	m_pNext = pNext;	// ポインタを再設定
}

//==================================================================================
// --- 怒り処理 ---
//==================================================================================
void CNextInfo::Angry(const int nAngryFrame)
{
	m_nAngryCount = nAngryFrame;		// フレーム数を設定
	
	if (m_pNext == nullptr) return;		// nullの場合スキップ

	// アイテム表示の描画をやめる
	m_pNext->SetDisp(false);

	// 怒り表示のテクスチャに切り替える
	m_pBase->BindTexture(CTexture::GetInstance()->Register(ANGRY_BASE));
}