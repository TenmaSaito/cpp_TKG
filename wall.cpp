#include "wall.h"

//==================================================================================
// --- 生成処理 ---
//==================================================================================
CWall *CWall::Create(const Vector3 &pos,
	const Vector3 &rot,
	const Vector2 &size)
{
	CWall *pWall = new CWall;		// 生成したオブジェクトへのポインタ
	if (pWall != nullptr)
	{ // 初期化処理
		pWall->Init(pos, rot, size);
	}

	return pWall;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CWall::CWall(const int nPriority) : CObject3D(nPriority)
{ // タイプを指定
	SetType(TYPE_WALL);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CWall::~CWall()
{
}

//==================================================================================
// --- 初期化処理 ---
//==================================================================================
HRESULT CWall::Init(const Vector3 &pos,
	const Vector3 &rot,
	const Vector2 &size)
{ // 親クラスの初期化
	return CObject3D::Init(Vector3(pos.x, pos.y + (size.y * 0.5f), pos.z), rot, size, true);
}

//==================================================================================
// --- 終了処理 ---
//==================================================================================
void CWall::Uninit(void)
{ // 親クラスの終了処理
	CObject3D::Uninit();
}

//==================================================================================
// --- 更新処理 ---
//==================================================================================
void CWall::Update(void)
{
}

//==================================================================================
// --- 描画処理 ---
//==================================================================================
void CWall::Draw(void)
{ // 親クラスの描画処理
	CObject3D::Draw();
}