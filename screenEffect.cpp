#include "screenEffect.h"
#include "manager.h"

//==================================================================================
// --- 生成処理 ---
//==================================================================================
CScreenEffect *CScreenEffect::Create(const Color &color,
	const float fFlashFrame)
{
	CScreenEffect *pScreenEffect = new CScreenEffect;		// 生成したオブジェクト
	if (pScreenEffect != nullptr)
	{ // ポインタが有効なため初期化
		pScreenEffect->Init(color, fFlashFrame);
	}

	return pScreenEffect;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CScreenEffect::CScreenEffect(const int nPriority) : CObject2D(nPriority)
{ // タイプ設定
	SetType(TYPE_SCREEN_EFFECT);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CScreenEffect::~CScreenEffect()
{
}

//==================================================================================
// --- 初期化処理 ---
//==================================================================================
HRESULT CScreenEffect::Init(const Color &color,
	const float fFlashFrame)
{ // フレーム数から一フレームの減少数を計算
	m_fAlphaDecrease = CManager::FrameToRatio(fFlashFrame);

	HRESULT hr = CObject2D::Init(SCREEN_MIDDLE, VECTOR3_NULL, SCREEN_SIZE);
	if (SUCCEEDED(hr))
	{ // 初期化成功時、色を変更
		SetColor(color);
	}

	return hr;
}

//==================================================================================
// --- 終了処理 ---
//==================================================================================
void CScreenEffect::Uninit(void)
{ // 親クラスの終了処理
	CObject2D::Uninit();
}

//==================================================================================
// --- 更新処理 ---
//==================================================================================
void CScreenEffect::Update(void)
{
	float fAlpha = GetColor().a;		// 現在のα値
	if (fAlpha > 0.0f)
	{ // 透明度が0以上なら減らす
		fAlpha -= m_fAlphaDecrease;
		SetAlpha((fAlpha < 0.0f) ? 0.0f : fAlpha);
	}
}

//==================================================================================
// --- 描画処理 ---
//==================================================================================
void CScreenEffect::Draw(void)
{ // 親クラスの描画処理
	CObject2D::Draw();
}

//==================================================================================
// --- フラッシュ処理 ---
//==================================================================================
void CScreenEffect::Flash(const float fAlpha)
{ // α値を1.0fに戻す
	SetAlpha(fAlpha);
}