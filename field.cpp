#include "field.h"

//==================================================================================
// --- 生成処理 ---
//==================================================================================
CField *CField::Create(const Vector3 &pos,
	const Vector3 &rot,
	const Vector2 &size)
{
	CField *pField = new CField;		// 生成したオブジェクトへのポインタ
	if (pField != nullptr)
	{ // 初期化処理
		pField->Init(pos, rot, size);
	}

	return pField;
}

//==================================================================================
// --- コンストラクタ ---
//==================================================================================
CField::CField(const int nPriority) : CObject3D(nPriority)
{ // タイプを指定
	SetType(TYPE_FIELD);
}

//==================================================================================
// --- デストラクタ ---
//==================================================================================
CField::~CField()
{
}

//==================================================================================
// --- 初期化処理 ---
//==================================================================================
HRESULT CField::Init(const Vector3 &pos,
	const Vector3 &rot,
	const Vector2 &size)
{ // 親クラスの初期化
	return CObject3D::Init(pos, rot, size);
}

//==================================================================================
// --- 終了処理 ---
//==================================================================================
void CField::Uninit(void)
{ // 親クラスの終了処理
	CObject3D::Uninit();
}

//==================================================================================
// --- 更新処理 ---
//==================================================================================
void CField::Update(void)
{ 
}

//==================================================================================
// --- 描画処理 ---
//==================================================================================
void CField::Draw(void)
{ // 親クラスの描画処理
	CObject3D::Draw();
}